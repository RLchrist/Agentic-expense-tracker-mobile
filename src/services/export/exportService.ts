import * as Print from 'expo-print'
import * as Sharing from 'expo-sharing'
import * as FileSystem from 'expo-file-system'
import { Expense } from '../../types'

// Export to CSV
export const exportToCSV = async (expenses: Expense[]): Promise<void> => {
  const headers = ['Date', 'Title', 'Amount', 'Currency', 'Category', 'Payment Method', 'Note']
  const rows = expenses.map((e) => [
    e.expense_date,
    `"${e.title.replace(/"/g, '""')}"`,
    e.amount,
    e.currency,
    `"${e.category?.name ?? 'Uncategorized'}"`,
    e.payment_method,
    `"${e.note?.replace(/"/g, '""') ?? ''}"`,
  ])

  const csv = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n')

  const fileUri = FileSystem.documentDirectory + 'expenses.csv'
  await FileSystem.writeAsStringAsync(fileUri, csv, {
    encoding: FileSystem.EncodingType.UTF8,
  })

  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(fileUri, {
      mimeType: 'text/csv',
      dialogTitle: 'Export Expenses CSV',
      UTI: 'public.comma-separated-values-text',
    })
  }
}

// Export to PDF
export const exportToPDF = async (
  expenses: Expense[],
  userName: string,
  period: string
): Promise<void> => {
  const total = expenses.reduce((s, e) => s + Number(e.amount), 0)

  const rows = expenses
    .sort((a, b) => new Date(b.expense_date).getTime() - new Date(a.expense_date).getTime())
    .map((e) => `
      <tr>
        <td>${e.expense_date}</td>
        <td>${e.title}</td>
        <td>${e.category?.name ?? 'Uncategorized'}</td>
        <td style="text-align:right">Rs. ${Number(e.amount).toLocaleString('en-NP')}</td>
        <td>${e.payment_method}</td>
        <td>${e.note ?? '-'}</td>
      </tr>
    `).join('')

  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8"/>
      <style>
        body { font-family: Arial, sans-serif; padding: 24px; color: #333; }
        h1 { color: #6C63FF; margin-bottom: 4px; }
        .meta { color: #888; font-size: 13px; margin-bottom: 24px; }
        table { width: 100%; border-collapse: collapse; font-size: 13px; }
        th { background: #6C63FF; color: white; padding: 10px 8px; text-align: left; }
        td { padding: 8px; border-bottom: 1px solid #eee; }
        tr:nth-child(even) { background: #f9f9f9; }
        .total { margin-top: 16px; text-align: right; font-size: 16px; font-weight: bold; color: #6C63FF; }
        .footer { margin-top: 32px; font-size: 11px; color: #aaa; text-align: center; }
      </style>
    </head>
    <body>
      <h1>💰 Expense Report</h1>
      <div class="meta">
        Generated for: <strong>${userName}</strong> &nbsp;|&nbsp;
        Period: <strong>${period}</strong> &nbsp;|&nbsp;
        Date: <strong>${new Date().toLocaleDateString()}</strong>
      </div>
      <table>
        <thead>
          <tr>
            <th>Date</th>
            <th>Title</th>
            <th>Category</th>
            <th style="text-align:right">Amount</th>
            <th>Payment</th>
            <th>Note</th>
          </tr>
        </thead>
        <tbody>${rows}</tbody>
      </table>
      <div class="total">Total: Rs. ${total.toLocaleString('en-NP', { minimumFractionDigits: 2 })}</div>
      <div class="footer">Generated by Expense Tracker App</div>
    </body>
    </html>
  `

  const { uri } = await Print.printToFileAsync({ html })
  const pdfUri = FileSystem.documentDirectory + `expenses-${period}.pdf`
  await FileSystem.moveAsync({ from: uri, to: pdfUri })

  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(pdfUri, {
      mimeType: 'application/pdf',
      dialogTitle: 'Export Expenses PDF',
    })
  }
}